package review.operator;

public class Operator03 {
    public static void main(String[] args) {
        int a = 2;
        int b = 3;
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a <= b);
        System.out.println(a >= b);
        boolean result = a == b; // = << 대입 연산자 우항을 연산하고 변수에 넘겨준다.

    }
}
